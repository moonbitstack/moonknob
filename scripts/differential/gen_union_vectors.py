"""Write the union test vectors from two implementations that know nothing of this
library, and check that they agree with each other before writing anything.

The cases are fixed by a generator written here rather than by `random`, so the
file is the same on every machine and in every year: a check that regenerates the
file would otherwise fail the day a Python release changed a shuffle. The first
opinion is CPython's dicts, the second is the JavaScript engine's own object
spread, run in Node. Where they differ the script stops instead of picking one.

Usage:
  python scripts/differential/gen_union_vectors.py          write src/union_vectors_test.mbt
  python scripts/differential/gen_union_vectors.py --check   fail if it is not what is on disk
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "src" / "union_vectors_test.mbt"
ORACLE = Path(__file__).resolve().parent / "union_oracle.mjs"

# Integer-like keys would be reordered by JavaScript objects, so the vocabulary is
# the header names of a JOSE token: all of them are ordinary strings.
KEYS = ["alg", "typ", "kid", "iss", "aud", "sub", "nbf", "exp", "jti", "cty"]


class Rng:
    """A 64-bit linear congruential generator; the same numbers everywhere."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) % 2**64
        return self.state >> 33

    def below(self, n):
        return self.next() % n

    def shuffle(self, items):
        for i in range(len(items) - 1, 0, -1):
            j = self.below(i + 1)
            items[i], items[j] = items[j], items[i]

    def side(self):
        """A map: nought to three of the vocabulary in a shuffled order, values 0
        to 2 so that the two sides agree on some keys and disagree on others. Short
        enough that a case stays one line each, which is what `moon fmt` leaves."""
        pool = KEYS[:]
        self.shuffle(pool)
        return [[key, self.below(3)] for key in pool[: self.below(4)]]


def cases():
    rng = Rng(20261114)
    out = []
    for _ in range(48):
        out.append({"base": rng.side(), "extra": rng.side()})
    return out


def from_python(case):
    """CPython's dicts: the merged map keeps the first side's order and takes
    the second side's value; a key only the second holds is added at the end."""
    base = dict(case["base"])
    extra = dict(case["extra"])
    names = [key for key, value in extra.items() if key in base and base[key] != value]
    extra_wins = dict(base)
    extra_wins.update(extra)
    base_wins = dict(base)
    for key, value in extra.items():
        if key not in base_wins:
            base_wins[key] = value
    return {
        "extra_wins": list(extra_wins.items()),
        "base_wins": list(base_wins.items()),
        "names": names,
    }


def from_node(payload):
    result = subprocess.run(
        ["node", str(ORACLE)],
        input=json.dumps(payload),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode != 0:
        sys.exit(f"the oracle did not run: {result.stderr.strip()}")
    answers = json.loads(result.stdout)
    for answer in answers:
        for side in ("extra_wins", "base_wins"):
            answer[side] = [tuple(pair) for pair in answer[side]]
    return answers


def pairs(items):
    return "[" + ", ".join(f'("{key}", {value})' for key, value in items) + "]"


def strings(items):
    return "[" + ", ".join(f'"{item}"' for item in items) + "]"


def render(cases, answers):
    body = []
    for case, answer in zip(cases, answers):
        body.append(
            "    {\n"
            f"      base: {pairs(case['base'])},\n"
            f"      extra: {pairs(case['extra'])},\n"
            f"      extra_wins: {pairs(answer['extra_wins'])},\n"
            f"      base_wins: {pairs(answer['base_wins'])},\n"
            f"      names: {strings(answer['names'])},\n"
            "    },"
        )
    return (
        "// Copyright 2026 Leo Cheng\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "//\n"
        "// Generated by scripts/differential/gen_union_vectors.py from CPython's dicts and\n"
        "// the JavaScript engine's object spread, which agreed on every case. Do not edit.\n"
        "\n"
        "///|\n"
        "/// One pair of maps and what both reference implementations made of them:\n"
        "/// the result when the second side wins, the result when the first does, and\n"
        "/// the keys they held with different values.\n"
        "priv struct UnionCase {\n"
        "  base : Array[(String, Int32)]\n"
        "  extra : Array[(String, Int32)]\n"
        "  extra_wins : Array[(String, Int32)]\n"
        "  base_wins : Array[(String, Int32)]\n"
        "  names : Array[String]\n"
        "}\n"
        "\n"
        "///|\n"
        "fn union_cases() -> Array[UnionCase] {\n"
        "  [\n" + "\n".join(body) + "\n  ]\n"
        "}\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    payload = cases()
    mine = [from_python(case) for case in payload]
    theirs = from_node(payload)
    if mine != theirs:
        for i, (a, b) in enumerate(zip(mine, theirs)):
            if a != b:
                sys.exit(f"case {i} disagrees: python {a} node {b}")
    page = render(payload, mine)
    before = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    OUT.write_text(page, encoding="utf-8", newline="\n")
    # The file is MoonBit, so `moon fmt` has the last word on its layout; running it
    # here is what keeps a formatted file and a generated one the same file.
    formatted = subprocess.run(["moon", "fmt", str(OUT.relative_to(ROOT))], cwd=ROOT, capture_output=True, text=True)
    if formatted.returncode != 0:
        sys.exit(f"moon fmt did not run: {formatted.stderr.strip() or formatted.stdout.strip()}")
    after = OUT.read_text(encoding="utf-8")
    if args.check and after != before:
        OUT.write_text(before, encoding="utf-8", newline="\n")
        sys.exit(f"{OUT.relative_to(ROOT)} is not what the vectors say; run the script")
    print(f"{OUT.relative_to(ROOT)}: {len(payload)} cases, both implementations agree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
